"""Generate a themeable coverage mask from the bundled Simple Icons SVG.

Generator only: Pillow + resvg-py 0.5.0. The DS build uses the generated header.
Install the renderer separately into tools/.cache/svg-render if desired.
"""
from io import BytesIO
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/.cache/svg-render'))
import resvg_py
from PIL import Image

svg = (ROOT / 'client/assets/soundcloud.svg').read_text(encoding='utf-8')
svg = svg.replace('viewBox="0 0 24 24"', 'viewBox="0 6 24 12"')
png = resvg_py.svg_to_bytes(svg_string=svg, width=288, height=144,
                           skip_system_fonts=True)
alpha = Image.open(BytesIO(png)).getchannel('A').resize((36, 18), Image.Resampling.LANCZOS)
values = [min(32, (value + 4) // 8) for value in alpha.tobytes()]
rows = [','.join(str(value) for value in values[y*36:(y+1)*36]) for y in range(18)]
header = ('// Generated by tools/generate_soundcloud_icon.py; Simple Icons, CC0.\n'
          '#pragma once\n#include <cstdint>\n'
          'constexpr uint8_t kSoundCloudCoverage[18][36] = {\n    {'
          + '},\n    {'.join(rows) + '}\n};\n')
(ROOT / 'client/include/soundcloud_icon.h').write_text(header, encoding='utf-8')
