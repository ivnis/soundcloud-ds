"""Generate the small Latin/Cyrillic subset of Gohufont (WTFPL)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "client/assets/gohufont-uni-11.bdf").read_text()
glyphs = {}
for block in source.split("STARTCHAR ")[1:]:
    code = int(re.search(r"ENCODING (\d+)", block)[1])
    width, height, x, y = map(int, re.search(r"BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", block).groups())
    rows = block.split("BITMAP\n", 1)[1].split("ENDCHAR", 1)[0].split()
    pixels = [0] * 11
    for row, bits in enumerate(rows):
        target = 9 - y - height + row
        if 0 <= target < 11:
            pixels[target] = (int(bits, 16) >> max(0, x)) & 255
    glyphs[code] = pixels
codes = list(range(32, 256)) + list(range(0x400, 0x500))
lines = ["// Generated by tools/generate_font.py. Gohufont, Hugo Chargois, WTFPL.",
         "#pragma once", "#include <cstdint>", "static constexpr uint8_t kFont[][11] = {"]
for code in codes:
    rows = glyphs.get(code, glyphs[ord("?")])
    lines.append("    {" + ",".join(f"0x{v:02x}" for v in rows) + f"}}, // U+{code:04X}")
lines.append("};")
(ROOT / "client/include/font_data.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated {len(codes)} glyphs; Cyrillic A present: {0x410 in glyphs}")
